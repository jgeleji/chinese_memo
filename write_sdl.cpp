static void poll_keys_file(void)
{
	if(!g_keysfile) return;
	if(!g_wait_for.empty())
	{
		// the pending command is a @WAIT: release it when the state matches
		if(g_state_last.find(g_wait_for) != std::string::npos) g_wait_for.clear();
		else return;
	}
	FILE* f = fopen(g_keysfile, "rb");
	if(!f) return;
	fseek(f, g_keysfile_pos, SEEK_SET);
	std::string got;
	int c;
	while((c = fgetc(f)) != EOF) got.push_back((char)c);
	fclose(f);
	if(!got.empty()) g_keysfile_pos += (long)got.size();

	// whole lines wait in a queue: a @WAIT must not discard the lines that
	// were already read past it (a previous version advanced the read offset
	// for the entire batch and then broke out of the loop - silent loss)
	static std::deque<std::string> queue;
	static std::string resid;
	got = resid + got;
	size_t nl = 0;
	for(;;)
	{
		size_t e = got.find('\n', nl);
		if(e == std::string::npos) break;
		queue.push_back(got.substr(nl, e - nl));
		nl = e + 1;
	}
	resid = got.substr(nl);

	while(!queue.empty())
	{
		std::string line = queue.front();
#ifdef CM_DEBUG
		fprintf(stderr, "dbg: keys line: %.40s\n", line.c_str());
#endif
		if(line.compare(0, 6, "@WAIT ") == 0)
		{
			g_wait_for = line.substr(6);
			while(!g_wait_for.empty() && (g_wait_for[0] == ' ' || g_wait_for[0] == '\t'))
				g_wait_for.erase(g_wait_for.begin());
			queue.pop_front();
			if(g_wait_for.empty()) continue;   // empty wait: treat as no-op
			return;                            // one command per poll cycle
		}
		queue.pop_front();
		if(line.compare(0, 5, "@TAP ") == 0)
		{
			int tx = 0, ty = 0;
			if(sscanf(line.c_str() + 5, "%d,%d", &tx, &ty) == 2) inject_tap(tx, ty);
			continue;
		}
		if(line.compare(0, 8, "@STROKE ") == 0)
		{
			std::vector<SDL_Point> pts;
			const char* q = line.c_str() + 8;
			for(;;)
			{
				int x, y, n;
				if(sscanf(q, " %d,%d%n", &x, &y, &n) != 2) break;
				SDL_Point p; p.x = x; p.y = y;
				pts.push_back(p);
				q += n;
			}
			if(!pts.empty())
			{
#ifdef CM_DEBUG
				fprintf(stderr, "dbg: stroke n=%zu first=%d,%d\n",
					pts.size(), pts[0].x, pts[0].y);
#endif
				inject_stroke(pts);
			}
			continue;
		}
		if(line == "@QUIT")
		{
			write_status();                     // never lose progress
			exit(0);
		}
		if(!line.empty() && line[0] != '#')
			fprintf(stderr, "write_sdl: unknown keys line: %s\n", line.c_str());
	}
}

