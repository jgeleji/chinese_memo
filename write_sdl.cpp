static void draw_poly(const std::vector<SDL_Point>& p, Uint32 col, int width)
{
	for(size_t i = 1; i < p.size(); ++i) draw_line(p[i-1].x, p[i-1].y, p[i].x, p[i].y, width, col);
	if(p.size() == 1) draw_circle(p[0].x, p[0].y, std::max(1, width / 2), col);
}

static void draw_scene(void)
{
	Uint32 now = SDL_GetTicks();

	int btn_px = std::max(24, std::min(56, g_w / 24));
	for(size_t i = 0; i < g_btns.size(); ++i)
	{
		const SDL_Rect& r = g_btns[i].first;
		fill_rect(r.x, r.y, r.w, r.h, COL_BTN);
		fill_rect(r.x, r.y, r.w, 2, COL_BTNBRD);
		fill_rect(r.x, r.y + r.h - 2, r.w, 2, COL_BTNBRD);
		fill_rect(r.x, r.y, 2, r.h, COL_BTNBRD);
		fill_rect(r.x + r.w - 2, r.y, 2, r.h, COL_BTNBRD);
		std::string label;
		Uint32 lc = COL_TEXT;
		switch(g_btns[i].second)
		{
			case BTN_MODE: label = g_learn ? "LEARN" : "QUIZ"; lc = g_learn ? COL_ACCENT : COL_TEXT; break;
			case BTN_SPLIT: label = g_split ? "SPLIT ON" : "SPLIT OFF"; lc = g_split ? COL_ACCENT : COL_DIM; break;
			case BTN_NEXT: label = "NEXT"; break;
		}
		int px = fit_px(label, r.w - 12, btn_px);
		draw_text_centered(label, lc, r.x + r.w / 2, r.y + r.h / 2, px);
	}

	// info line (character + reading) and the source word, above the box
	std::string py;
	std::unordered_map<std::string, std::string>::iterator p = g_pinyin.find(g_qchar);
	if(p != g_pinyin.end()) py = p->second;
	int info_px = std::max(40, std::min(110, g_w / 11));
	std::string head = g_qchar + (py.empty() ? "" : "  " + py);
	draw_text_centered(head, COL_TEXT, g_w / 2, g_box.y - info_px - 10, info_px);
	{
		std::string wl = g_qword.cn + "  -  " + g_qword.en;
		int wpx = std::max(22, std::min(48, g_w / 26));
		wpx = fit_px(wl, g_w - 24, wpx);
		draw_text_centered(wl, COL_DIM, g_w / 2, g_box.y - 12, wpx);
	}

	if(g_phase == PH_PICK)
	{
		draw_box_grid(g_box, COL_GRID2, COL_GRID);
		int px = (int)(g_box.s * 0.55);
		draw_text_centered(g_qchar, COL_GRID2, g_box.x + g_box.s / 2, g_box.y + g_box.s * 0.2, px);
		std::string hint = "which parts, and in what order?  " +
			std::to_string(g_pick_pos) + "/" + std::to_string((int)g_comps.size());
		int hpx = fit_px(hint, g_box.s, std::max(24, std::min(52, g_w / 24)));
		draw_text_centered(hint, COL_DIM, g_box.x + g_box.s / 2, g_box.y + g_box.s * 0.82, hpx);
		for(size_t i = 0; i < g_cands.size() && i < g_cand_boxes.size(); ++i)
		{
			Box b = g_cand_boxes[i];
			draw_box_grid(b, COL_BTNBRD, COL_GRID);
			draw_text_centered(g_cands[i], COL_TEXT, b.x + b.s / 2, b.y + b.s / 2, (int)(b.s * 0.7));
		}
	}
	else
	{
		if(!g_qsplit) draw_box_grid(g_box, COL_GRID2, COL_GRID);
		for(size_t i = 0; i < g_sub_boxes.size(); ++i)
			draw_box_grid(g_sub_boxes[i], i == (size_t)g_comp_idx ? COL_ACCENT : COL_GRID2, COL_GRID);

		int ink_w = std::max(3, box_for_scope().s / 24);
		for(size_t i = 0; i < g_done_px.size(); ++i) draw_poly(g_done_px[i], COL_INK, ink_w);
		if(g_learn && g_phase == PH_DRAW)
		{
			for(size_t i = g_stroke_idx; i < g_scope.size(); ++i)
			{
				const StrokeRef& sr = g_qcd->strokes[g_scope[i]];
				std::vector<SDL_Point> rp;
				for(size_t j = 0; j < sr.pts.size(); ++j) rp.push_back(g_mapper.map(sr.pts[j]));
				draw_poly(rp, i == g_stroke_idx ? COL_SKELE : COL_GRID2, std::max(3, ink_w * 2 / 3));
				if(i == g_stroke_idx)
					draw_circle(rp.front().x, rp.front().y, std::max(4, ink_w), COL_SKELE);
			}
		}
		if(now < g_err_until) draw_poly(g_err_path, COL_FAIL, ink_w);
		if(g_capturing) draw_poly(g_live, COL_LIVE, ink_w);
	}

	if(g_phase == PH_DONE)
	{
		draw_text_centered(g_qchar, COL_OK, g_box.x + g_box.s / 2, g_box.y + g_box.s / 2,
			(int)(g_box.s * 0.8));
		draw_text_centered("OK", COL_OK, g_box.x + g_box.s / 2, g_box.y + g_box.s * 0.9,
			std::max(26, std::min(56, g_w / 24)));
	}

	// footer: stroke progress + feedback
	int foot_px = std::max(26, std::min(50, g_w / 26));
	std::string prog;
	if(g_phase == PH_PICK)
		prog = "parts " + std::to_string(g_pick_pos) + "/" + std::to_string((int)g_comps.size());
	else
		prog = "stroke " + std::to_string(std::min((int)g_stroke_idx + 1, (int)g_scope.size())) +
		       "/" + std::to_string((int)g_scope.size());
	draw_text(prog, COL_DIM, std::max(12, g_w / 30), g_box.y + g_box.s + foot_px, foot_px);
	if(!g_fb.empty() && now < g_fb_until)
	{
		int fpx = fit_px(g_fb, g_w * 0.6, foot_px);
		draw_text(g_fb, g_fb_col, g_w / 2, g_box.y + g_box.s + foot_px, fpx);
	}
}

