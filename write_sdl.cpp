static void draw_circle(int cx, int cy, int r, Uint32 color)
{
	for(int dy = -r; dy <= r; ++dy)
		for(int dx = -r; dx <= r; ++dx)
			if(dx * dx + dy * dy <= r * r)
			{
				int x = cx + dx, y = cy + dy;
				if(x < 0 || x >= g_w || y < 0 || y >= g_h) continue;
				g_pixels[(size_t)y * g_w + x] = color;
			}
	if(r > 0) mark_dirty(cx - r, cy - r, cx + r + 1, cy + r + 1);
}

static void draw_line(int x0, int y0, int x1, int y1, int width, Uint32 color)
{
	float dx = (float)(x1 - x0), dy = (float)(y1 - y0);
	float len = sqrtf(dx * dx + dy * dy);
	int r = std::max(1, width / 2);
	if(len < 1.0f) { draw_circle(x0, y0, r, color); return; }
	int steps = (int)(len) + 1;
	for(int i = 0; i <= steps; ++i)
		draw_circle(x0 + (int)(dx * i / steps), y0 + (int)(dy * i / steps), r, color);
}

