// flat ⿰⿱⿲⿳ with single-char children we have data for (v1 split support)
static bool can_split(const CharData& cd, std::vector<std::string>& comps)
{
	comps.clear();
	if(cd.ids.empty()) return false;
	const std::string& op = cd.ids[0];
	int n = 2;
	if(op == "\u2ff2" || op == "\u2ff3") n = 3;
	else if(op != "\u2ff0" && op != "\u2ff1") return false;
	if((int)cd.ids.size() < 1 + n) return false;
	for(int i = 1; i <= n; ++i)
		if(!g_chars.count(cd.ids[i])) return false;
	comps.assign(cd.ids.begin() + 1, cd.ids.begin() + 1 + n);
	if(cd.comp.size() != cd.strokes.size()) return false;
	for(size_t i = 0; i < cd.comp.size(); ++i)
		if(cd.comp[i] < 0 || cd.comp[i] >= n) return false;
	return true;
}

static bool is_op_vert(const std::string& op)
{ return op == "\u2ff1" || op == "\u2ff3"; }

static void next_question(void)
{
	if(g_order_pos >= g_word_order.size())
	{
		std::shuffle(g_word_order.begin(), g_word_order.end(), g_rng);
		g_order_pos = 0;
	}
	g_qword = g_words[g_word_order[g_order_pos++]];

	// among the word's characters practice the one with the worst record
	std::string best = g_qword.hanzi[0];
	int best_score = -1000000;
	for(size_t i = 0; i < g_qword.hanzi.size(); ++i)
	{
		const std::string& c = g_qword.hanzi[i];
		int score = g_fail[c] * 3 - g_ok[c];
		if(score > best_score) { best_score = score; best = c; }
	}
	g_qchar = best;
	g_qcd = &g_chars[g_qchar];

	std::vector<std::string> comps;
	g_qsplit = g_split && can_split(*g_qcd, comps);
	if(g_qsplit)
	{
		g_comps = comps;
		g_pick_pos = 0;
		g_phase = PH_PICK;
		// candidates: the right components + up to two dummies, shuffled
		g_cands = g_comps;
		int want = (int)g_comps.size() + std::min(2, 3 - (int)g_comps.size());
		std::unordered_set<std::string> have(g_cands.begin(), g_cands.end());
		int guard = 0;
		while((int)g_cands.size() < want && !g_comp_pool.empty() && guard++ < 40)
		{
			const std::string& d = g_comp_pool[g_rng() % g_comp_pool.size()];
			if(!have.count(d)) { have.insert(d); g_cands.push_back(d); }
		}
		std::shuffle(g_cands.begin(), g_cands.end(), g_rng);
	}
	else
	{
		g_comps.clear();
		begin_draw_scope();
	}
	g_done_px.clear();
	g_err_path.clear();
	g_live.clear();
	g_fb.clear();
}

static void handle_pick_tap(int x, int y)
{
	for(size_t i = 0; i < g_cands.size() && i < g_cand_boxes.size(); ++i)
	{
		if(!box_has(g_cand_boxes[i], x, y, 0)) continue;
		if(g_cands[i] == g_comps[g_pick_pos])
		{
			++g_pick_pos;
			if(g_pick_pos >= (int)g_comps.size()) begin_draw_scope();
			else set_fb("now " + g_comps[g_pick_pos], COL_DIM);
		}
		else set_fb("wrong part: write " + g_comps[g_pick_pos] + " first", COL_FAIL);
		return;
	}
}

