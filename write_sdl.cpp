struct Pt { double x, y; };

struct StrokeRef
{
	std::vector<Pt> pts;   // data units (0..1024, y is UP)
	double len;            // polyline length in data units
	double chord_dir;      // atan2 angle of start->end, radians (y up)
	double bend;           // angle between the first segment and the chord
};

struct CharData
{
	std::vector<std::string> ids;   // IDS tokens ("⿰ 女 子"); empty if none
	std::vector<int> comp;          // component index per stroke; empty if none
	std::vector<StrokeRef> strokes;
};

static std::unordered_map<std::string, CharData> g_chars;
static double g_minx = 0, g_miny = 0, g_maxx = 1, g_maxy = 1;

static void derive(StrokeRef& s)
{
	s.len = 0;
	for(size_t i = 1; i < s.pts.size(); ++i)
	{
		double dx = s.pts[i].x - s.pts[i-1].x, dy = s.pts[i].y - s.pts[i-1].y;
		s.len += sqrt(dx * dx + dy * dy);
	}
	double cx = s.pts.back().x - s.pts[0].x, cy = s.pts.back().y - s.pts[0].y;
	s.chord_dir = atan2(cy, cx);
	if(s.pts.size() > 1)
	{
		double sx = s.pts[1].x - s.pts[0].x, sy = s.pts[1].y - s.pts[0].y;
		double a = atan2(sy, sx) - s.chord_dir;
		while(a > M_PI) a -= 2 * M_PI;
		while(a < -M_PI) a += 2 * M_PI;
		s.bend = fabs(a);
	}
	else s.bend = 0;
}

static std::vector<std::string> split_tab(const std::string& s)
{
	std::vector<std::string> out;
	size_t i = 0;
	while(i <= s.size())
	{
		size_t j = s.find('\t', i);
		if(j == std::string::npos) { out.push_back(s.substr(i)); break; }
		out.push_back(s.substr(i, j - i));
		i = j + 1;
	}
	return out;
}

static bool load_write_data(const char* path)
{
	FILE* f = fopen(path, "rb");
	if(!f) return false;
	char* line = NULL;
	size_t cap = 0;
	ssize_t n;
	while((n = getline(&line, &cap, f)) != -1)
	{
		std::string s(line, (size_t)n);
		while(!s.empty() && (s[s.size()-1] == '\n' || s[s.size()-1] == '\r')) s.erase(s.size()-1);
		if(s.empty()) continue;
		if(s.compare(0, 3, "#G ") == 0)
		{
			sscanf(s.c_str() + 3, "%lf %lf %lf %lf", &g_minx, &g_miny, &g_maxx, &g_maxy);
			continue;
		}
		std::vector<std::string> f_ = split_tab(s);
		if(f_.size() < 4) continue;
		CharData cd;
		if(f_[1] != "*")
		{
			std::string ids = f_[1];
			size_t i = 0;
			while(i < ids.size())
			{
				while(i < ids.size() && ids[i] == ' ') ++i;
				size_t j = ids.find(' ', i);
				if(j == std::string::npos) j = ids.size();
				if(j > i) cd.ids.push_back(ids.substr(i, j - i));
				i = j;
			}
		}
		if(f_[2] != "-")
		{
			const char* q = f_[2].c_str();
			for(;;)
			{
				int v, adv;
				if(sscanf(q, "%d%n", &v, &adv) != 1) break;
				cd.comp.push_back(v);
				q += adv;
				if(*q == ',') ++q;
			}
		}
		for(size_t k = 3; k < f_.size(); ++k)
		{
			StrokeRef sr;
			const char* q = f_[k].c_str();
			for(;;)
			{
				double x, y;
				int adv;
				if(sscanf(q, " %lf %lf%n", &x, &y, &adv) != 2) break;
				Pt p; p.x = x; p.y = y;
				sr.pts.push_back(p);
				q += adv;
			}
			if(sr.pts.empty()) continue;
			derive(sr);
			cd.strokes.push_back(sr);
		}
		if(!cd.strokes.empty()) g_chars[f_[0]] = cd;
	}
	free(line);
	fclose(f);
	return !g_chars.empty();
}

