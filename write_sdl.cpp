struct Mapper
{
	double sc;             // data units -> px
	double cxm, cym;       // content centre in data units
	Box box;
	SDL_Point map(const Pt& p) const
	{
		SDL_Point r;
		r.x = (int)(box.x + box.s / 2.0 + (p.x - cxm) * sc);
		r.y = (int)(box.y + box.s / 2.0 - (p.y - cym) * sc);   // y is UP in data
		return r;
	}
};

static Mapper make_mapper(const CharData& cd, const std::vector<size_t>& scope, Box box)
{
	Mapper m;
	m.box = box;
	double x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
	for(size_t i = 0; i < scope.size(); ++i)
		for(size_t j = 0; j < cd.strokes[scope[i]].pts.size(); ++j)
		{
			const Pt& p = cd.strokes[scope[i]].pts[j];
			x0 = std::min(x0, p.x); y0 = std::min(y0, p.y);
			x1 = std::max(x1, p.x); y1 = std::max(y1, p.y);
		}
	double dx = std::max(1.0, x1 - x0), dy = std::max(1.0, y1 - y0);
	m.sc = 0.88 * box.s / std::max(dx, dy);   // 12% padding inside the box
	m.cxm = (x0 + x1) / 2.0;
	m.cym = (y0 + y1) / 2.0;
	return m;
}

static Mapper g_mapper;

static double path_len(const std::vector<SDL_Point>& p)
{
	double t = 0;
	for(size_t i = 1; i < p.size(); ++i)
	{
		double dx = p[i].x - p[i-1].x, dy = p[i].y - p[i-1].y;
		t += sqrt(dx * dx + dy * dy);
	}
	return t;
}

static double ang_diff(double a, double b)
{
	double d = a - b;
	while(d > M_PI) d -= 2 * M_PI;
	while(d < -M_PI) d += 2 * M_PI;
	return fabs(d);
}

// ---------------------------------------------------------------------------
// grading: tolerances are fractions of the practice box side S
// ---------------------------------------------------------------------------

static const double TOL_START = 0.15;   // start point off
static const double TOL_LEN   = 0.15;   // chord length off
static const double TOL_SHAPE = 0.15;   // mean resampled polyline distance
static const double TOL_DIR   = 15.0 * M_PI / 180.0;

static void resample16(const std::vector<SDL_Point>& p, std::vector<SDL_Point>& out)
{
	out.clear();
	if(p.size() < 2)
	{
		SDL_Point z = p.empty() ? SDL_Point{0, 0} : p[0];
		for(int i = 0; i < 16; ++i) out.push_back(z);
		return;
	}
	double total = path_len(p);
	if(total < 1.0) { for(int i = 0; i < 16; ++i) out.push_back(p[0]); return; }
	size_t seg = 0;
	double acc = 0;
	for(int i = 0; i < 16; ++i)
	{
		double want = total * i / 15.0;
		for(;;)
		{
			double sl = hypot(p[seg+1].x - p[seg].x, p[seg+1].y - p[seg].y);
			if(seg + 1 >= p.size() || acc + sl >= want) break;
			acc += sl;
			++seg;
		}
		double sl = seg + 1 < p.size() ? hypot(p[seg+1].x - p[seg].x, p[seg+1].y - p[seg].y) : 0;
		double f = sl > 0 ? (want - acc) / sl : 0;
		if(f < 0) f = 0;
		if(f > 1) f = 1;
		SDL_Point q;
		q.x = (int)(p[seg].x + f * (p[seg+1].x - p[seg].x));
		q.y = (int)(p[seg].y + f * (p[seg+1].y - p[seg].y));
		out.push_back(q);
	}
}

struct Grade { bool ok; std::string why; };

// user path in window px, reference mapped to the same space by g_mapper
static Grade grade_stroke(const StrokeRef& ref, const std::vector<SDL_Point>& user, Box box)
{
	Grade gr;
	gr.ok = false;
	double S = (double)box.s;
	std::vector<SDL_Point> rp;
	for(size_t i = 0; i < ref.pts.size(); ++i) rp.push_back(g_mapper.map(ref.pts[i]));

	double ulen = path_len(user);
	double rlen = ref.len * g_mapper.sc;

	// a dot: short reference; just land near it, do not overshoot far
	if(rlen < 0.06 * S)
	{
		double d = hypot(user.front().x - rp.front().x, user.front().y - rp.front().y);
		if(d <= 0.18 * S && ulen <= 0.30 * S) { gr.ok = true; return gr; }
		gr.why = "miss the dot";
		return gr;
	}

	// shape fallback: fair for hooks/bends when the whole sweep is right
	if(ulen > 6.0)
	{
		std::vector<SDL_Point> a, b;
		resample16(rp, a);
		resample16(user, b);
		double sum = 0;
		for(int i = 0; i < 16; ++i) sum += hypot(a[i].x - b[i].x, a[i].y - b[i].y);
		if(sum / 16.0 <= TOL_SHAPE * S) { gr.ok = true; return gr; }
	}

	// start point
	if(hypot(user.front().x - rp.front().x, user.front().y - rp.front().y) > TOL_START * S)
	{ gr.why = "start too far"; return gr; }
	if(ulen < 0.10 * S)
	{ gr.why = "too short: draw the whole stroke"; return gr; }

	// direction (both chords measured in window px, so the y flip cancels)
	double ua = atan2((double)(user.back().y - user.front().y), (double)(user.back().x - user.front().x));
	double ra = atan2((double)(rp.back().y - rp.front().y), (double)(rp.back().x - rp.front().x));
	double dtol = TOL_DIR + std::min(20.0 * M_PI / 180.0, ref.bend);
	if(ang_diff(ua, ra) > dtol) { gr.why = "wrong direction"; return gr; }

	// length
	if(fabs(ulen - rlen) > TOL_LEN * S) { gr.why = "wrong length"; return gr; }

	gr.ok = true;
	return gr;
}

