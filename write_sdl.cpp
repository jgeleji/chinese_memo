static void mark_dirty(int x0, int y0, int x1, int y1)
{
	if(x0 < 0) x0 = 0;
	if(y0 < 0) y0 = 0;
	if(x1 > g_w) x1 = g_w;
	if(y1 > g_h) y1 = g_h;
	if(x0 >= x1 || y0 >= y1) return;
	if(g_damage.w <= 0)
	{
		g_damage.x = x0; g_damage.y = y0; g_damage.w = x1 - x0; g_damage.h = y1 - y0;
		return;
	}
	int rx1 = g_damage.x + g_damage.w, ry1 = g_damage.y + g_damage.h;
	if(x0 < g_damage.x) g_damage.x = x0;
	if(y0 < g_damage.y) g_damage.y = y0;
	if(x1 > rx1) rx1 = x1;
	if(y1 > ry1) ry1 = y1;
	g_damage.w = rx1 - g_damage.x;
	g_damage.h = ry1 - g_damage.y;
}

static void fill_rect(int x, int y, int w, int h, Uint32 color)
{
	if(w <= 0 || h <= 0) return;
	int x0 = std::max(0, x), y0 = std::max(0, y);
	int x1 = std::min(g_w, x + w), y1 = std::min(g_h, y + h);
	if(x0 >= x1 || y0 >= y1) return;
	for(int yy = y0; yy < y1; ++yy)
		std::fill_n(g_pixels + (size_t)yy * g_w + x0, x1 - x0, color);
	mark_dirty(x0, y0, x1, y1);
}

