// ---------------------------------------------------------------------------
// chinese write - stroke-order writing practice (SDL2, Android + desktop)
//
// Practice app on the chinese_memo word base: the user draws every stroke of
// a character as a finger drag inside a practice box. Each stroke is graded
// against the Make Me a Hanzi median of the intended stroke: the start point
// must be within 15% of the box side, the chord direction within 15 degrees
// (widened automatically for bent strokes), the chord length within 15% of
// the box side; plus a shape-match fallback (both polylines resampled to 16
// points, mean distance <= 15% of the box side) so curved strokes are graded
// fairly.
//
// Top buttons: LEARN/QUIZ (show the stroke skeleton or not), SPLIT on/off
// (component mode: tap the components in writing order, then draw each one
// in its own sub-box; only for flat IDS operators with single-char children),
// NEXT to skip the character. Progress lives in wstatus.txt - status1.txt
// belongs to the quiz app and status2.txt to questions10hsk.
//
// Data files (generated by tools/gen_write_data.py, see its header):
//   write_data.txt    "#G minx miny maxx maxy" header; then per line:
//       char \t "IDS tokens"|* \t component index per stroke (comma)|- \t
//       strokes joined by tabs, each stroke "x y" pairs, y UP, 0..1024 scale
//   write_pinyin.txt  char \t pinyin
//   union_q.txt       the word base, "chinese|english" per line
//   wstatus.txt       progress: char|pinyin|ok|fail rows
//
// Headless driver hooks (same spirit as the quiz app's CM_* protocol):
//   CM_WINDOW=WxH        desktop window size
//   CM_SEED=N            deterministic question order
//   CM_KEYS_FILE=f       script lines appended by the driver, consumed in
//     order, one pending command at a time:
//       @WAIT <substr>   stall until the state line contains <substr>
//       @TAP x,y         synthetic tap at window pixels
//       @STROKE x,y x,y ...  synthetic finger drag through the points; goes
//                        through the exact same capture+grading path as a
//                        real finger (this is what makes stroke tests real)
//       @QUIT            flush final state and exit
//   CM_STATE_FILE=f      rewritten every frame with one line:
//     WAIT seq=N phase=draw|pick|done stroke=i/n comp=c/k frame=F box=x,y,s
//          mode=learn|quiz split=on|off ok=T fail=F word=<w> char=<c>
//          pinyin=<p> comps=<a b c>| whole=1 [cands=<女@x,y,s;...>]
//   CM_DUMP_DIR=d (or file "cm_dump_dir")     dumps frame%03d.png + .txt
//   CM_MAXFRAMES=n (or file "cm_maxframes")   stop after n dumped frames
// ---------------------------------------------------------------------------

