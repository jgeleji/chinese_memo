static void draw_box_grid(Box b, Uint32 edge, Uint32 inner)
{
	int w = std::max(2, b.s / 200);
	fill_rect(b.x, b.y, b.s, w, edge);
	fill_rect(b.x, b.y + b.s - w, b.s, w, edge);
	fill_rect(b.x, b.y, w, b.s, edge);
	fill_rect(b.x + b.s - w, b.y, w, b.s, edge);
	int cw = std::max(1, w / 2);
	int cx = b.x + b.s / 2, cy = b.y + b.s / 2;
	fill_rect(cx - cw / 2, b.y + w, cw, b.s - 2 * w, inner);
	fill_rect(b.x + w, cy - cw / 2, b.s - 2 * w, cw, inner);
	for(int i = 0; i <= 40; ++i)   // the 米字格 diagonals, faint
	{
		int t = b.s * i / 40;
		draw_circle(b.x + t, b.y + t, cw, inner);
		draw_circle(b.x + b.s - t, b.y + t, cw, inner);
	}
}

static void compute_layout(void)
{
	int m = std::max(12, g_w / 30);
	int bh = std::max(46, std::min(96, g_w / 18));
	int bw = (g_w - 2 * m) / 3;
	g_btns.clear();
	for(int i = 0; i < 3; ++i)
	{
		SDL_Rect r;
		r.x = m + i * bw; r.y = m; r.w = bw - m / 2; r.h = bh;
		g_btns.push_back(std::make_pair(r, i));
	}

	int top = m + bh + m / 2;
	int foot_h = std::max(26, std::min(50, g_w / 26)) * 3;
	int avail_h = g_h - top - foot_h - m;
	int s = std::min(g_w - 2 * m, avail_h);
	s = std::max(120, s);
	g_box.x = (g_w - s) / 2;
	g_box.y = top + (avail_h - s) / 2;
	g_box.s = s;

	g_sub_boxes.clear();
	if(g_qsplit && !g_comps.empty())
	{
		int n = (int)g_comps.size();
		int gap = s / 12;
		bool vert = !g_qcd->ids.empty() && is_op_vert(g_qcd->ids[0]);
		int cs = (s - (n - 1) * gap) / n;
		for(int i = 0; i < n; ++i)
		{
			Box b;
			b.s = cs;
			if(vert)
			{
				b.x = g_box.x + (g_box.s - cs) / 2;
				b.y = g_box.y + i * (cs + gap);
			}
			else
			{
				b.y = g_box.y + (g_box.s - cs) / 2;
				b.x = g_box.x + i * (cs + gap);
			}
			g_sub_boxes.push_back(b);
		}
	}

	g_cand_boxes.clear();
	if(g_phase == PH_PICK && !g_cands.empty())
	{
		int n = (int)g_cands.size();
		int gap = g_box.s / 10;
		int cs = (g_box.s - (n - 1) * gap) / n;
		cs = std::min(cs, g_box.s * 2 / 3);
		int total_w = n * cs + (n - 1) * gap;
		for(int i = 0; i < n; ++i)
		{
			Box b;
			b.s = cs;
			b.x = g_box.x + (g_box.s - total_w) / 2 + i * (cs + gap);
			b.y = g_box.y + (g_box.s - cs) / 2;
			g_cand_boxes.push_back(b);
		}
	}

	if(g_phase == PH_DRAW && !g_scope.empty())
		g_mapper = make_mapper(*g_qcd, g_scope, box_for_scope());
}

