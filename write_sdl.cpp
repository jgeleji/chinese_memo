static bool handle_tap(int x, int y)
{
#ifdef CM_DEBUG
	fprintf(stderr, "dbg: tap %d,%d nbtn=%zu", x, y, g_btns.size());
	for(size_t dbg_i = 0; dbg_i < g_btns.size(); ++dbg_i)
		fprintf(stderr, " [%d,%d %dx%d id%d]", g_btns[dbg_i].first.x, g_btns[dbg_i].first.y,
			g_btns[dbg_i].first.w, g_btns[dbg_i].first.h, g_btns[dbg_i].second);
	fprintf(stderr, " phase=%d\n", (int)g_phase);
#endif
	for(size_t i = 0; i < g_btns.size(); ++i)
	{
		const SDL_Rect& r = g_btns[i].first;
		if(x < r.x || x > r.x + r.w || y < r.y || y > r.y + r.h) continue;
		switch(g_btns[i].second)
		{
			case BTN_MODE:
				g_learn = !g_learn;   // takes effect live, no restart needed
				return true;
			case BTN_SPLIT:
				g_split = !g_split;
				if(!g_word_order.empty() && g_order_pos > 0) --g_order_pos;
				next_question();
				return true;
			case BTN_NEXT:
				write_status();
				next_question();
				return true;
		}
		return true;
	}
	if(g_phase == PH_PICK) { handle_pick_tap(x, y); return true; }
	return false;
}

static void inject_tap(int x, int y) { handle_tap(x, y); }

