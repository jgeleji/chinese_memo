static std::string build_state_line(void)
{
	const char* ph = g_phase == PH_PICK ? "pick" : (g_phase == PH_DONE ? "done" : "draw");
	Box b = g_phase == PH_PICK ? g_box : box_for_scope();
	int tot_ok = 0, tot_fail = 0;
	for(std::unordered_map<std::string, int>::iterator it = g_ok.begin(); it != g_ok.end(); ++it) tot_ok += it->second;
	for(std::unordered_map<std::string, int>::iterator it = g_fail.begin(); it != g_fail.end(); ++it) tot_fail += it->second;
	std::string py;
	std::unordered_map<std::string, std::string>::iterator p = g_pinyin.find(g_qchar);
	if(p != g_pinyin.end()) py = p->second;

	char buf[2048];
	snprintf(buf, sizeof(buf),
		"WAIT seq=%ld phase=%s stroke=%d/%d comp=%d/%d frame=%d box=%d,%d,%d "
		"mode=%s split=%s ok=%d fail=%d word=%s char=%s pinyin=%s",
		g_wait_seq, ph, (int)g_stroke_idx + 1, (int)g_scope.size(),
		g_comp_idx + 1, (int)g_comps.size(), g_dump_counter,
		b.x, b.y, b.s,
		g_learn ? "learn" : "quiz", g_split ? "on" : "off",
		tot_ok, tot_fail, g_qword.cn.c_str(), g_qchar.c_str(), py.c_str());
	std::string s(buf);
	if(g_phase == PH_PICK)
	{
		char pb[64];
		snprintf(pb, sizeof(pb), " pick=%d/%d", g_pick_pos, (int)g_comps.size());
		s += pb;
		s += " cands=";
		for(size_t i = 0; i < g_cands.size() && i < g_cand_boxes.size(); ++i)
		{
			if(i) s += ";";
			char cb[128];
			snprintf(cb, sizeof(cb), "%s@%d,%d,%d", g_cands[i].c_str(),
				g_cand_boxes[i].x, g_cand_boxes[i].y, g_cand_boxes[i].s);
			s += cb;
		}
	}
	return s;
}

static void write_state_line(void)
{
	if(!g_statefile) return;
	FILE* f = fopen(g_statefile, "w");
	if(!f) return;
	fprintf(f, "%s\n", g_state_last.c_str());
	fclose(f);
	++g_wait_seq;
}

