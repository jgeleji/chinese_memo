static bool box_has(Box b, int x, int y, int margin)
{
	return x >= b.x - margin && x <= b.x + b.s + margin &&
	       y >= b.y - margin && y <= b.y + b.s + margin;
}

static void set_fb(const std::string& msg, Uint32 col)
{
	g_fb = msg;
	g_fb_col = col;
	g_fb_until = SDL_GetTicks() + 1500;
}

static Box box_for_scope(void);   // layout helper, defined further below

static std::vector<size_t> scope_for(int comp)
{
	std::vector<size_t> s;
	for(size_t i = 0; i < g_qcd->strokes.size(); ++i)
		if(comp < 0 || (i < g_qcd->comp.size() && g_qcd->comp[i] == comp)) s.push_back(i);
	return s;
}

static void enter_next_scope_or_done(void);

static void finish_stroke(void)
{
	const StrokeRef& ref = g_qcd->strokes[g_scope[g_stroke_idx]];
	Grade gr = grade_stroke(ref, g_live, box_for_scope());
#ifdef CM_DEBUG
	fprintf(stderr, "dbg: grade stroke idx=%zu n=%zu live=%zu ok=%d why=%s\n",
		g_stroke_idx, g_scope.size(), g_live.size(), (int)gr.ok, gr.why.c_str());
#endif
	if(gr.ok)
	{
		g_done_px.push_back(g_live);
		g_fb.clear();
		++g_stroke_idx;
		enter_next_scope_or_done();
	}
	else
	{
		g_err_path = g_live;
		g_err_until = SDL_GetTicks() + 700;
		g_fail[g_qchar]++;
		set_fb(gr.why + " - try again", COL_FAIL);
	}
	g_live.clear();
}

static void begin_draw_scope(void)
{
	g_comp_idx = g_qsplit ? 0 : -1;
	g_scope = scope_for(g_comp_idx);
	g_stroke_idx = 0;
	g_phase = PH_DRAW;
	g_live.clear();
}

static void enter_next_scope_or_done(void)
{
	// the current scope is only exhausted once every stroke in it is done;
	// in split mode that is also the only moment we may move to the next
	// component (a previous version advanced the component on every stroke,
	// skipping the rest of each component)
	if(g_stroke_idx < g_scope.size()) return;
	if(g_qsplit && g_comp_idx + 1 < (int)g_comps.size())
	{
		++g_comp_idx;
		g_scope = scope_for(g_comp_idx);
		g_stroke_idx = 0;
		set_fb(g_comps[g_comp_idx] + " now", COL_DIM);
		return;
	}
	g_ok[g_qchar]++;
	write_status();
	g_phase = PH_DONE;
	g_done_until = SDL_GetTicks() + 1200;
}

static void stroke_begin(int x, int y)
{
	if(g_phase != PH_DRAW)
	{
#ifdef CM_DEBUG
		fprintf(stderr, "dbg: stroke_begin phase!=draw (%d)\n", (int)g_phase);
#endif
		return;
	}
	if(!box_has(box_for_scope(), x, y, 40))
	{
#ifdef CM_DEBUG
		fprintf(stderr, "dbg: stroke_begin outside box %d,%d,%d tap=%d,%d\n",
			box_for_scope().x, box_for_scope().y, box_for_scope().s, x, y);
#endif
		return;
	}
	g_capturing = true;
	g_live.clear();
	SDL_Point p; p.x = x; p.y = y;
	g_live.push_back(p);
}

static void stroke_move(int x, int y)
{
	if(!g_capturing || g_live.empty()) return;
	if(hypot(x - g_live.back().x, y - g_live.back().y) < 3.0) return;
	SDL_Point p; p.x = x; p.y = y;
	g_live.push_back(p);
}

static void stroke_end(void)
{
	if(!g_capturing) return;
	g_capturing = false;
	if(!g_live.empty()) finish_stroke();
}

static void inject_stroke(const std::vector<SDL_Point>& pts)
{
	if(pts.empty()) return;
	stroke_begin(pts[0].x, pts[0].y);
	for(size_t i = 1; i < pts.size(); ++i) stroke_move(pts[i].x, pts[i].y);
	stroke_end();
}

