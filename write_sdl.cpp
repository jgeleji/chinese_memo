static void recreate_surface(int w, int h)
{
	if(g_texture) SDL_DestroyTexture(g_texture);
	delete[] g_pixels;
	g_texture = NULL;
	g_pixels = NULL;
	g_w = w; g_h = h;
	g_texture = SDL_CreateTexture(g_renderer, SDL_PIXELFORMAT_ARGB8888, SDL_TEXTUREACCESS_STATIC, g_w, g_h);
	g_pixels = new Uint32[(size_t)g_w * g_h];
	std::fill_n(g_pixels, (size_t)g_w * g_h, COL_BG);
	g_full_repaint = true;
}

static void present(void)
{
	if(!g_texture) return;
	g_damage = g_full_repaint ? SDL_Rect{0, 0, g_w, g_h} : g_prev_damage;
	g_full_repaint = false;
	fill_rect(g_damage.x, g_damage.y, g_damage.w, g_damage.h, COL_BG);
	draw_scene();
	if(g_damage.w > 0 && g_damage.h > 0)
	{
		bool ok = (SDL_UpdateTexture(g_texture, &g_damage, g_pixels + (size_t)g_damage.y * g_w, g_w * 4) == 0);
		if(ok) ok = (SDL_RenderCopy(g_renderer, g_texture, &g_damage, &g_damage) == 0);
		if(!ok) g_full_repaint = true;
		SDL_RenderPresent(g_renderer);
	}
	g_prev_damage = g_damage;
}

int main(int argc, char** argv)
{
	(void)argc; (void)argv;
	// Android (and any touch device) makes SDL synthesize a MOUSE event for
	// every touch: one tap would then be handled twice - the SPLIT toggle
	// "did nothing" (on->off->on) and picking the right component was followed
	// by a phantom tap on the NEXT slot ("always the wrong part"). Kill the
	// cross-synthesis and also filter the legacy mouse id for touch below.
	SDL_SetHint(SDL_HINT_MOUSE_TOUCH_EVENTS, "0");
	SDL_SetHint(SDL_HINT_TOUCH_MOUSE_EVENTS, "0");

	if(SDL_Init(SDL_INIT_VIDEO) != 0)
	{
		fprintf(stderr, "SDL_Init failed: %s\n", SDL_GetError());
		return 1;
	}

	int w = 0, h = 0;
#ifndef __ANDROID__
	if(getenv("CM_WINDOW")) sscanf(getenv("CM_WINDOW"), "%dx%d", &w, &h);
#endif
	if(w <= 0 || h <= 0)
	{
		SDL_DisplayMode dm;
		if(SDL_GetDesktopDisplayMode(0, &dm) == 0) { w = dm.w; h = dm.h; }
		else { w = 1080; h = 1920; }
	}
	Uint32 flags = 0;
#ifdef __ANDROID__
	flags |= SDL_WINDOW_FULLSCREEN_DESKTOP;
#else
	if(getenv("SDL_VIDEODRIVER") && strcmp(getenv("SDL_VIDEODRIVER"), "dummy") == 0)
		flags |= SDL_WINDOW_RESIZABLE;
#endif
	g_window = SDL_CreateWindow("chinese_write", 0, 0, w, h, flags);
	if(!g_window)
	{
		fprintf(stderr, "SDL_CreateWindow failed: %s\n", SDL_GetError());
		return 1;
	}
	g_renderer = SDL_CreateRenderer(g_window, -1, SDL_RENDERER_SOFTWARE);
	if(!g_renderer) g_renderer = SDL_CreateRenderer(g_window, -1, 0);
	if(!g_renderer)
	{
		fprintf(stderr, "SDL_CreateRenderer failed: %s\n", SDL_GetError());
		return 1;
	}
	int dw = 0, dh = 0;
	SDL_GL_GetDrawableSize(g_window, &dw, &dh);
	if(dw <= 0 || dh <= 0) SDL_GetWindowSize(g_window, &dw, &dh);
	recreate_surface(dw > 0 ? dw : w, dh > 0 ? dh : h);

	FILE* f = fopen("NotoSansSC.ttf", "rb");
	if(!f) f = fopen("assets/NotoSansSC.ttf", "rb");
	if(f)
	{
		fseek(f, 0, SEEK_END);
		long sz = ftell(f);
		fseek(f, 0, SEEK_SET);
		g_fontdata.resize((size_t)sz);
		size_t got = fread(&g_fontdata[0], 1, (size_t)sz, f);
		fclose(f);
		if((long)got == sz && stbtt_InitFont(&g_font, &g_fontdata[0], stbtt_GetFontOffsetForIndex(&g_fontdata[0], 0)))
			g_font_ok = true;
	}
	if(!g_font_ok)
	{
		fprintf(stderr, "chinese_write: FATAL: failed to load NotoSansSC.ttf from the working directory\n");
		return 1;
	}

	const char* seed = getenv("CM_SEED");
	if(seed && seed[0]) g_rng.seed((unsigned)atoi(seed));
	else g_rng.seed((unsigned)(time(NULL) ^ (unsigned)SDL_GetTicks()));
	g_statefile = getenv("CM_STATE_FILE");
	g_keysfile = getenv("CM_KEYS_FILE");
	if(g_keysfile) g_scripted = true;

	if(!load_write_data("write_data.txt"))
	{
		fprintf(stderr, "chinese_write: FATAL: cannot read write_data.txt from the working directory\n");
		return 1;
	}
	load_pinyin("write_pinyin.txt");
	load_words("union_q.txt");
	load_status("wstatus.txt");
	if(g_words.empty())
	{
		fprintf(stderr, "chinese_write: FATAL: no usable words in union_q.txt\n");
		return 1;
	}
	for(size_t i = 0; i < g_words.size(); ++i) g_word_order.push_back(i);

	std::unordered_set<std::string> pool;
	for(std::unordered_map<std::string, CharData>::iterator it = g_chars.begin(); it != g_chars.end(); ++it)
		for(size_t i = 1; i < it->second.ids.size(); ++i)
			if(utf8_is_han(it->second.ids[i]) && g_chars.count(it->second.ids[i]))
				pool.insert(it->second.ids[i]);
	g_comp_pool.assign(pool.begin(), pool.end());
	SDL_Log("chinese_write: chars=%zu words=%zu pool=%zu window=%dx%d",
		g_chars.size(), g_words.size(), g_comp_pool.size(), g_w, g_h);

	next_question();

	int mouse_down = 0;
	for(;;)
	{
		poll_keys_file();

		SDL_Event ev;
		if(g_scripted)
		{
			while(SDL_PollEvent(&ev))
				if(ev.type == SDL_QUIT) { write_status(); return 0; }
			SDL_Delay(10);
		}
		else
		{
			// idle timeout must NOT skip the frame: the state file (and the
			// fading feedback text) need a repaint every so often even when
			// nothing is tapping
			bool got_ev = (SDL_WaitEventTimeout(&ev, 120) != 0);
			if(got_ev) do
			{
				switch(ev.type)
				{
					case SDL_QUIT:
						write_status();
						return 0;
					case SDL_FINGERDOWN:
						if(!handle_tap((int)(ev.tfinger.x * g_w), (int)(ev.tfinger.y * g_h)))
							stroke_begin((int)(ev.tfinger.x * g_w), (int)(ev.tfinger.y * g_h));
						break;
					case SDL_FINGERMOTION:
						stroke_move((int)(ev.tfinger.x * g_w), (int)(ev.tfinger.y * g_h));
						break;
					case SDL_FINGERUP:
						stroke_end();
						break;
					case SDL_MOUSEBUTTONDOWN:
						if(ev.button.which == SDL_TOUCH_MOUSEID) break;  // real mouse only
						if(ev.button.button == SDL_BUTTON_LEFT)
						{
							mouse_down = 1;
							if(!handle_tap(ev.button.x, ev.button.y))
								stroke_begin(ev.button.x, ev.button.y);
						}
						break;
					case SDL_MOUSEMOTION:
						if(ev.motion.which == SDL_TOUCH_MOUSEID) break;
						if(mouse_down && (ev.motion.state & SDL_BUTTON_LMASK))
							stroke_move(ev.motion.x, ev.motion.y);
						break;
					case SDL_MOUSEBUTTONUP:
						if(ev.button.which == SDL_TOUCH_MOUSEID) break;
						if(ev.button.button == SDL_BUTTON_LEFT && mouse_down)
						{
							mouse_down = 0;
							stroke_end();
						}
						break;
					case SDL_KEYDOWN:
						if(ev.key.keysym.sym == SDLK_ESCAPE || ev.key.keysym.sym == SDLK_AC_BACK)
						{
							write_status();
							return 0;
						}
						break;
					case SDL_WINDOWEVENT:
						if(ev.window.event == SDL_WINDOWEVENT_SIZE_CHANGED ||
						   ev.window.event == SDL_WINDOWEVENT_RESIZED)
						{
							int nw = 0, nh = 0;
							SDL_GL_GetDrawableSize(g_window, &nw, &nh);
							if(nw <= 0 || nh <= 0) SDL_GetWindowSize(g_window, &nw, &nh);
							if(nw > 0 && nh > 0 && (nw != g_w || nh != g_h)) recreate_surface(nw, nh);
						}
						break;
					default:
						break;
				}
			} while(SDL_PollEvent(&ev));
		}

		if(g_phase == PH_DONE && SDL_GetTicks() > g_done_until) next_question();

		g_frame_notes.clear();
		g_frame_notes.push_back("word: " + g_qword.cn + " | " + g_qword.en);
		if(!g_fb.empty()) g_frame_notes.push_back("feedback: " + g_fb);

		compute_layout();
		g_state_last = build_state_line();
		present();
		dump_frame();
		write_state_line();
	}
}
