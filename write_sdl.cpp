struct Run { std::string text; Uint32 fg; };

static void blit_runs(const std::vector<Run>& runs, int x, float baseline, int def_px)
{
	int x_cur = x;
	for(size_t i = 0; i < runs.size(); ++i)
	{
		const Run& r = runs[i];
		int px = def_px;
		GlyphCache* gc = cache_for(px);
		if(!gc) continue;
		const unsigned char* p = (const unsigned char*)r.text.data();
		const unsigned char* e = (const unsigned char*)r.text.data() + r.text.size();
		double fx = (double)x_cur;
		while(p < e)
		{
			unsigned int cp;
			const unsigned char* q = utf8_next(p, e, cp);
			if(cp == 0) break;
			const Glyph* gb = gc->get(cp);
			if(gb)
			{
				int gx0 = (int)floor(fx + (double)gb->xoff);
				int gy0 = (int)floor(baseline + (double)gb->yoff);
				int gw = gb->w, gh = gb->h;
				for(int row = 0; row < gh; ++row)
				{
					int dy = gy0 + row;
					if(dy < 0 || dy >= g_h) continue;
					const unsigned char* src = &gc->bmp[(size_t)(gb->y0 + row) * gc->w + gb->x0];
					for(int col = 0; col < gw; ++col)
					{
						int dx = gx0 + col;
						if(dx < 0 || dx >= g_w) continue;
						unsigned int cov = src[col];
						if(!cov) continue;
						Uint32* dst = &g_pixels[(size_t)dy * g_w + dx];
						unsigned int a = cov;
						Uint32 f = r.fg;
						Uint32 dr = (*dst) >> 16 & 0xFF, dg = (*dst) >> 8 & 0xFF, db = (*dst) & 0xFF;
						Uint32 fr = f >> 16 & 0xFF, fg2 = f >> 8 & 0xFF, fb = f & 0xFF;
						Uint32 nr = (fr * a + dr * (255 - a)) / 255;
						Uint32 ng = (fg2 * a + dg * (255 - a)) / 255;
						Uint32 nb = (fb * a + db * (255 - a)) / 255;
						*dst = 0xFF000000u | (nr << 16) | (ng << 8) | nb;
					}
				}
				mark_dirty(gx0, gy0, gx0 + gw, gy0 + gh);
				fx += (double)gb->advance;
			}
			else fx += (double)px * 0.5;
			p = q;
		}
		x_cur = (int)floor(fx);
	}
}

static double measure_text(const std::string& text, int px)
{
	GlyphCache* gc = cache_for(px);
	return gc ? measure_range(gc, text, 0, text.size(), px) : 0.0;
}

// draw left-aligned at (x, top-of-line)
static void draw_text(const std::string& text, Uint32 fg, int x, int y_top, int px)
{
	std::vector<Run> runs;
	Run r; r.text = text; r.fg = fg;
	runs.push_back(r);
	blit_runs(runs, x, (float)y_top + font_baseline(px), px);
}

static void draw_text_centered(const std::string& text, Uint32 fg, int cx, int cy, int px)
{
	double w = measure_text(text, px);
	int h = px;
	draw_text(text, fg, (int)(cx - w / 2.0), (int)(cy - h / 2.0), px);
}

// shrink px until the text fits into max_w
static int fit_px(const std::string& text, double max_w, int px)
{
	while(px > 14 && measure_text(text, px) > max_w) px = (int)(px * 0.92);
	return px;
}

